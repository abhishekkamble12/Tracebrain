"""Write ui/src/lib/cypher.generated.ts: the exact Cypher each MCP tool runs, for the UI's
"Show Cypher" drawer. Generated from tracebrain/queries.py so the UI can't drift from the backend
(tests/test_ui_cypher.py fails if the file is stale).

    uv run python scripts/export_cypher_for_ui.py
"""

import json
from pathlib import Path

from tracebrain import queries

OUT = Path(__file__).resolve().parents[1] / "ui" / "src" / "lib" / "cypher.generated.ts"

# tool -> queries it runs, in order (mirrors tracebrain/tools/impl.py). `role` says why.
TOOL_QUERIES: dict[str, list[tuple[str, str]]] = {
    "get_incident": [("INCIDENT", "incident, its alert and the service it fired on")],
    "blast_radius": [("BLAST_RADIUS", "every upstream service whose path to the failing one is valid at t")],
    "owners_of": [("OWNERS", "owning team valid at t, and its people")],
    "suspects": [
        ("SUSPECTS", "deploys in the window on the as-of dependency closure (0-3 hops), with path edge ids"),
        ("SERVICE_FAIL_COUNTS", "earlier incidents per candidate service (fail_rate feature)"),
        ("PAGERANK", "structural prior (centrality feature)"),
        ("RECALL_LESSONS", "confirmed lessons for this symptom (lesson_match feature, memory ON only)"),
    ],
    "page_priority": [
        ("BLAST_RADIUS", "the failing service's callers, as of t"),
        ("ASOF_DEPENDENCY_IDS", "the dependency edges valid at t (cache key: one computation per topology)"),
        ("DROP_EDGES_NOT_AS_OF", "on a throwaway GRAPH.COPY: delete every edge not valid at t"),
        ("BETWEENNESS", "betweenness on that as-of copy: the ranking that picks who is paged"),
        ("PAGERANK", "PageRank on the same copy (tie-break)"),
        ("OWNERS", "owning team valid at t, and its people"),
    ],
    "path_between": [("SHORTEST_PATH", "shortest dependency path valid at t")],
    "centrality": [("PAGERANK", "PageRank over DEPENDS_ON"), ("BETWEENNESS", "betweenness over DEPENDS_ON")],
    "write_finding": [("ADD_FINDING", "blackboard write, scoped to this investigation")],
    "read_findings": [("FINDINGS", "findings earlier agents wrote, with their HANDOFF edges")],
    "recall_similar": [("RECALL_SIMILAR", "human-confirmed incidents with the same symptom, before t")],
    "recall_lessons": [("RECALL_LESSONS", "confirmed lessons for this symptom and service, before t")],
    "get_past_investigation": [
        ("PAST_INCIDENT_INVESTIGATION", "the confirmed investigation of that incident"),
        ("STEPS", "its tool sequence"),
        ("HYPOTHESES", "its hypotheses and verified claims"),
    ],
}
WRITES = {"write_finding"}


def render() -> str:
    names = sorted({q for qs in TOOL_QUERIES.values() for q, _ in qs})
    texts = {n: getattr(queries, n).strip() for n in names}
    tools = {t: [{"name": q, "role": r} for q, r in qs] for t, qs in TOOL_QUERIES.items()}
    return (
        "// GENERATED by scripts/export_cypher_for_ui.py from tracebrain/queries.py. Do not edit.\n"
        "// tests/test_ui_cypher.py fails if this file is out of date.\n\n"
        f"export const CYPHER: Record<string, string> = {json.dumps(texts, indent=2)};\n\n"
        "export interface ToolQuery { name: string; role: string }\n\n"
        f"export const TOOL_QUERIES: Record<string, ToolQuery[]> = {json.dumps(tools, indent=2)};\n\n"
        f"export const WRITE_TOOLS: string[] = {json.dumps(sorted(WRITES))};\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")
